#!/usr/bin/env bash
# Writes chips' golden trees to tests/golden/chips.ts; runs only on the hooks at its pin.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(cd "$HERE/../.." && pwd)"
PLUGIN="$ROOT/plugins/nextcost"; OUT="$HERE/out"; mkdir -p "$OUT"
PIN=846e17d
git -C "$ROOT" cat-file -e "$PIN^{commit}" 2>/dev/null || { echo "capture.sh: pin $PIN is not in this clone" >&2; exit 1; }
if ! git -C "$ROOT" diff --quiet "$PIN" -- plugins/nextcost/hooks; then
  echo "capture.sh: hooks/ differs from $PIN; the capture must come from the band as chips' 0.13 board draws it" >&2
  exit 1
fi
# The hooks are the pin's, whatever HEAD is, so the header names the pin.
COMMIT="$(git -C "$ROOT" rev-parse "$PIN")"
# Run in a scratch copy holding only what the capture imports, so it never
# depends on the golden suite or the chips.ts it is about to replace. The
# cases come from cases.ts, never matrix.ts, which imports the views.
SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
find "$PLUGIN" -mindepth 1 -maxdepth 1 ! -name tests -exec cp -R {} "$SCRATCH/" \;
mkdir -p "$SCRATCH/tests/golden"
cp "$PLUGIN"/tests/{helpers.ts,cases.ts,globals.d.ts} "$SCRATCH/tests/"
cp "$PLUGIN/tests/golden/hash.ts" "$SCRATCH/tests/golden/"
cp "$HERE/capture.test.ts" "$SCRATCH/tests/golden-capture.test.ts"
START_S=$(date +%s)
claude plugin test "$SCRATCH" > "$OUT/capture.log" 2>&1 || { tail -30 "$OUT/capture.log"; exit 1; }
echo "capture took $(( $(date +%s) - START_S ))s"
python3 - "$OUT/capture.log" "$PLUGIN/tests/golden/chips.ts" "$COMMIT" <<'EOF'
import json, re, sys
log, out, commit = open(sys.argv[1]).read().splitlines(), sys.argv[2], sys.argv[3]
golden = dict(re.match(r'GOLDEN (\S+) (\S+)$', l).groups() for l in log if l.startswith('GOLDEN '))
trees = {m.group(1): json.loads(m.group(2)) for l in log if (m := re.match(r'TREE (\S+) (.+)$', l))}
assert len(golden) == 20 * 2 * 6 * 2, f'expected 480 cases, got {len(golden)}'
assert len(trees) == 10, f'expected 10 trees, got {len(trees)}'
with open(out, 'w') as f:
    f.write(f'// Generated by tools/golden/capture.sh from {commit}\'s hooks, the band as\n')
    f.write("// chips' 0.13 board draws it. Frozen: a change here must be justified in\n")
    f.write('// review.\n\n')
    f.write('export const GOLDEN: Readonly<Record<string, string>> = ' + json.dumps(golden, indent=1, sort_keys=True) + '\n\n')
    f.write('export const GOLDEN_TREES: Readonly<Record<string, unknown>> = ' + json.dumps(trees, sort_keys=True) + '\n')
print(len(golden), 'cases,', len(trees), 'trees')
EOF
grep '^PERF' "$OUT/capture.log"
